export function getLiveCard(sheetId: SideDeskCheatSheetId, cardId: string): SideDeskLiveCard | undefined {
  return SIDE_DESK_LIVE_CATALOGS[sheetId].cards.find((c) => c.id === cardId);
}

export function cardsForFlowStep(sheetId: SideDeskCheatSheetId, flowStepId: string): SideDeskLiveCard[] {
  const catalog = SIDE_DESK_LIVE_CATALOGS[sheetId];
  const step = catalog.flowSteps.find((s) => s.id === flowStepId) ?? catalog.flowSteps[0]!;
  return step.cardIds
    .map((id) => catalog.cards.find((c) => c.id === id))
    .filter((c): c is SideDeskLiveCard => Boolean(c));
}
